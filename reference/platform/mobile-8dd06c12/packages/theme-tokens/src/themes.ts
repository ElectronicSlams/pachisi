import type { ThemeId, ThemeMaterial, ThemeMode, ThemeTokens, TokenName } from "./contract";
import { THEME_IDS } from "./contract";

type ThemeInput = {
  readonly id: ThemeId;
  readonly mode: ThemeMode;
  readonly color: Record<TokenName, string>;
  readonly material: ThemeMaterial;
};

function freezeRecord<T extends object>(value: T): Readonly<T> {
  return Object.freeze(value);
}

function defineTheme(input: ThemeInput): ThemeTokens {
  const color = freezeRecord({ ...input.color });
  const material = freezeRecord({ ...input.material });
  const ink = freezeRecord({
    mark: color.accent,
    pieceA: color.pieceDark,
    pieceB: color.pieceLight,
  });
  return Object.freeze({ id: input.id, mode: input.mode, color, ink, material });
}

